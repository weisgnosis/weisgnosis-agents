package com.weisgnosis.agents.core.model

import scala.compiletime.testing.typeCheckErrors
import zio.*
import zio.json.*
import zio.test.*

/** Pure construction and explicit identity allocation adapt the seven upstream DataBlockTest methods. */
object DataBlockSpec extends ZIOSpecDefault:
  def spec: Spec[TestEnvironment, Any] = suite("DataBlockSpec")(
    test("testBuildWithUrlSource") {
      val block = ContentBlock.Data.url("https://example.com/cat.png", Some("cat.png"))
      for identified <- block.identified
      yield assertTrue(
        block.source == MediaSource.Url("https://example.com/cat.png"),
        block.name.contains("cat.png"),
        block.id.isEmpty,
        identified.id.exists(_.nonEmpty),
        identified.copy(id = None) == block
      )
    },
    test("testBuildWithBase64Source") {
      val block =
        ContentBlock.Data(MediaSource.Base64("image/png", "iVBORw0KGgo="), Some("fixed-id"))
      assertTrue(
        block.source == MediaSource.Base64("image/png", "iVBORw0KGgo="),
        block.id.contains("fixed-id"),
        block.name.isEmpty
      )
    },
    test("testJsonRoundTrip") {
      val block = ContentBlock.Data(
        MediaSource.Url("https://example.com/x.mp3"),
        Some("abc123"),
        Some("x.mp3")
      )
      val json = block.toJson
      assertTrue(
        json.fromJson[ContentBlock.Data].contains(block),
        json.fromJson[ContentBlock].contains(block),
        json.contains("\"type\":\"data\""),
        json.contains("\"id\":\"abc123\""),
        json.contains("\"name\":\"x.mp3\"")
      )
    },
    test("testJsonDeserializationViaContentBlock") {
      val json =
        """{"type":"data","source":{"type":"url","url":"https://example.com/v.mp4"},"id":"vid-1","name":"v.mp4"}"""
      assertTrue(
        json
          .fromJson[ContentBlock]
          .contains(
            ContentBlock
              .Data(MediaSource.Url("https://example.com/v.mp4"), Some("vid-1"), Some("v.mp4"))
          )
      )
    },
    test("testIdAutoGenerated") {
      val first  = ContentBlock.Data.url("https://example.com/a")
      val second = ContentBlock.Data.url("https://example.com/b")
      for
        _ <- TestRandom.setSeed(42L)
        a <- first.identified
        b <- second.identified
      yield assertTrue(
        a.id.exists(_.nonEmpty),
        b.id.exists(_.nonEmpty),
        a.id != b.id,
        first.id.isEmpty,
        second.id.isEmpty
      )
    },
    test("testNameIsOptional") {
      val block = ContentBlock.Data.url("https://example.com/x.png")
      assertTrue(
        block.name.isEmpty,
        !block.toJson.contains("\"name\""),
        block.toJson.fromJson[ContentBlock.Data].contains(block)
      )
    },
    test("testNullSourceRejected") {
      val invalid =
        Chunk("""{"type":"data","name":"x"}""", """{"type":"data","source":null,"name":"x"}""")
      assertTrue(
        typeCheckErrors(
          """com.weisgnosis.agents.core.model.ContentBlock.Data(name = Some("x"))"""
        ).nonEmpty,
        typeCheckErrors("""com.weisgnosis.agents.core.model.ContentBlock.Data(None)""").nonEmpty,
        invalid.forall(json =>
          json.fromJson[ContentBlock.Data].isLeft && json.fromJson[ContentBlock].isLeft
        )
      )
    },
    test("identity allocation is suspended and reusing an identity consumes no randomness") {
      val original = ContentBlock.Data.url("https://example.com/data", Some("name"))
      for
        _ <- TestRandom.setSeed(19L)
        allocation = original.identified
        expectedFirst  <- Random.nextUUID
        _              <- TestRandom.setSeed(19L)
        allocated      <- allocation
        reused         <- allocated.identified
        after          <- Random.nextUUID
        _              <- TestRandom.setSeed(19L)
        _              <- Random.nextUUID
        expectedSecond <- Random.nextUUID
      yield assertTrue(
        allocated.id.contains(expectedFirst.toString),
        reused == allocated,
        after == expectedSecond,
        allocated.copy(id = None) == original,
        original.id.isEmpty,
        original.toJson.fromJson[ContentBlock.Data].contains(original)
      )
    }
  )
